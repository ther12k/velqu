// ---------------------------------------------------------------- bundle

export interface BundleResult {
  code: string;
  sourceMap: string | null;
}

export async function bundleApp(
  app: ExtractedApp,
  opts: { sourceMap?: boolean } = {},
): Promise<BundleResult> {
  // synthetic entry: registers handler/policy references from the app modules
  // WITHOUT evaluating any handler/service (COMP-002: Bun.build bundles, never runs)
  const importFiles = [...new Set([...app.routes.map((r) => r.sourceFile), ...app.policies.map((p) => p.sourceFile)])];
  const imports: string[] = [];
  const registers: string[] = [];
  const nsNames = new Map<string, string>();
  importFiles.forEach((f, i) => {
    const ns = `m${i}`;
    nsNames.set(f, ns);
    const rel = relative(app.entryFile, f);
    imports.push(`import * as ${ns} from ${JSON.stringify(rel)};`);
  });
  for (const r of app.routes) {
    const ns = nsNames.get(r.sourceFile)!;
    registers.push(`__velquRegister(${JSON.stringify(r.id)});`);
  }
  const manifestElements: string[] = [];
  for (const r of app.routes) {
    const ns = nsNames.get(r.sourceFile)!;
    const isDefault = r.bindingName === "__default_export";
    manifestElements.push(`[${JSON.stringify(r.id)}, 0, function (ctx) { return (${ns}.${isDefault ? "default" : r.bindingName}).handle(ctx); }]`);
  }
  for (const p of app.policies) {
    const ns = nsNames.get(p.sourceFile)!;
    manifestElements.push(`[${JSON.stringify(p.id)}, 1, function (req) { return (${ns}.${p.bindingName}).check(req); }]`);
  }

  // Direct vector dispatch with semantic function manifest (M2.3-r3):
  const entry = `// @generated by @velqu/compiler — do not edit\n${imports.join("\n")}\n\nglobalThis.__velquFunctionManifest = [\n  ${manifestElements.join(",\n  ")}\n];\nglobalThis.__velquFunctions = globalThis.__velquFunctionManifest.map(function (e) { return e[2]; });\n`;

  // write synthetic entry to a temp file next to the real entry so relative imports resolve
  const tmpEntry = app.entryFile.replace(/\.ts$/, ".__velqu_entry__.ts");
  const { writeFileSync: wf } = await import("node:fs");
  wf(tmpEntry, entry);
  try {
    const result = await Bun.build({
      entrypoints: [tmpEntry],
      target: "bun",
      format: "esm",
      sourcemap: opts.sourceMap === false ? "none" : "linked",
      minify: false, // keep readable + deterministic
    });
    if (!result.success) {
      const msgs = result.logs.map((l) => String(l)).join("\n");
      throw new Error(`bundle failed:\n${msgs}`);
    }
    const out = result.outputs[0];
    const code = await out.text();
    let sourceMap: string | null = null;
    const mapOut = result.outputs.find((o) => o.path.endsWith(".js.map") || o.kind === "sourcemap");
    if (mapOut) sourceMap = await mapOut.text();
    else if (opts.sourceMap !== false) {
      // "linked" emits .map next to output; fetch by convention
      try {
        const mapPath = out.path + ".map";
        sourceMap = await Bun.file(mapPath).text();
      } catch {
        sourceMap = null;
      }
    }
    return { code, sourceMap };
  } finally {
    const { unlinkSync } = await import("node:fs");
    try {
      unlinkSync(tmpEntry);
    } catch {}
  }
}

function relative(from: string, to: string): string {
  // both absolute-ish repo paths; emit a relative import from entry dir
  const { dirname, relative: rel } = require("node:path") as typeof import("node:path");
  let r = rel(dirname(from), to).replace(/\\/g, "/");
  if (!r.startsWith(".")) r = "./" + r;
  return r.replace(/\.ts$/, ".ts");
}

// ---------------------------------------------------------------- IR → pack structures

function segsFor(path: string): Array<{ kind: string; value: string }> {
  return path
    .split("/")
    .filter(Boolean)
    .map((s) =>
      s.startsWith(":")
        ? { kind: "param", value: s.slice(1) }
        : s.startsWith("*")
          ? { kind: "wildcard", value: "" }
          : { kind: "static", value: s },
    );
}

export function schemaRegistry(app: ExtractedApp): Record<string, unknown> {
  const reg: Record<string, unknown> = {};
  const put = (key: string, ir: Record<string, unknown> | null) => {
    if (ir) reg[key] = ir;
  };
  for (const r of app.routes) {
    put(`sch:${r.id}.params`, r.paramsIr);
    put(`sch:${r.id}.query`, r.queryIr);
    put(`sch:${r.id}.body`, r.bodyIr);
    for (const [status, decl] of Object.entries(r.responses)) {
      if (decl.ir && !decl.problem) put(`sch:${r.id}.${status}`, decl.ir);
    }
  }
  return reg;
}

/**
 * Canonical JSON form (M25-001-C, ADR-0023): every object's keys are sorted
 * recursively (code-unit order), arrays keep their order. Mirrors
 * `q_schema_runtime::canonical_value` — both sides hash the same canonical
 * string regardless of source literal field order.
 */
function sortIR(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortIR);
  if (v && typeof v === "object") {
    const o = v as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(o).sort()) out[k] = sortIR(o[k]);
    return out;
  }
  return v;
}

/** Rust-canonical: the whole execution-graph view passes through sortIR. */
function rustCanonical(
  routes: unknown[],
  schemas: Record<string, unknown>,
  policies: unknown,
  capabilities: string[],
  functions: unknown[],
  schemaManifest: unknown[],
  policyManifest: unknown[],
  router: unknown,
): string {
  return JSON.stringify(
    sortIR({
      routes,
      schemas,
      policies,
      capabilities,
      functions,
      schemaManifest,
      policyManifest,
      router,
    }),
  );
}

function buildSerializedRouter(routes: Array<{ method: string; pathSegments: Array<{ kind: string; value: string }> }>) {
  const methodMap: Record<string, number> = {
    GET: 0,
    POST: 1,
    PUT: 2,
    PATCH: 3,
    DELETE: 4,
    OPTIONS: 5,
    HEAD: 6,
  };
  const nodes: Array<{
    staticEdges: Array<{ segment: string; targetNode: number }>;
    paramEdge: number | null;
    wildcardEdge: number | null;
    terminal: { methodMask: number; routeByMethod: Array<number | null> } | null;
  }> = [
    { staticEdges: [], paramEdge: null, wildcardEdge: null, terminal: null },
  ];

  for (let rIdx = 0; rIdx < routes.length; rIdx++) {
    const r = routes[rIdx];
    let curr = 0;
    for (const seg of r.pathSegments) {
      if (seg.kind === "static") {
        const existing = nodes[curr].staticEdges.find((e) => e.segment === seg.value);
        if (existing) {
          curr = existing.targetNode;
        } else {
          const next = nodes.length;
          nodes.push({ staticEdges: [], paramEdge: null, wildcardEdge: null, terminal: null });
          nodes[curr].staticEdges.push({ segment: seg.value, targetNode: next });
          curr = next;
        }
      } else if (seg.kind === "param") {
        if (nodes[curr].paramEdge !== null) {
          curr = nodes[curr].paramEdge!;
        } else {
          const next = nodes.length;
          nodes.push({ staticEdges: [], paramEdge: null, wildcardEdge: null, terminal: null });
          nodes[curr].paramEdge = next;
          curr = next;
        }
      } else if (seg.kind === "wildcard") {
        if (nodes[curr].wildcardEdge !== null) {
          curr = nodes[curr].wildcardEdge!;
        } else {
          const next = nodes.length;
          nodes.push({ staticEdges: [], paramEdge: null, wildcardEdge: null, terminal: null });
          nodes[curr].wildcardEdge = next;
          curr = next;
        }
      }
    }
    if (!nodes[curr].terminal) {
      nodes[curr].terminal = {
        methodMask: 0,
        routeByMethod: [null, null, null, null, null, null, null],
      };
    }
    const mIdx = methodMap[r.method.toUpperCase()] ?? 0;
    nodes[curr].terminal!.methodMask |= 1 << mIdx;
    nodes[curr].terminal!.routeByMethod[mIdx] = rIdx;
  }
  return { nodes };
}


/** M26-002-A: sha256 hex via Bun — mirrors q-pack's hex(&Sha256::digest()). */
function sha256Hex(input: string): string {
  return new Bun.CryptoHasher("sha256").update(input).digest("hex");
}

/** Runtime identity tuple hash — MUST equal q_pack::runtime_build_hash(). */
function runtimeBuildHash(): string {
  return sha256Hex("abi=1:engine=quickjs-ng:version=0.15.1:rquickjs=0.12.2:binding=rquickjs-0.12.2");
}

/** Capability-set hash — MUST equal q_pack::capability_hash(). */
function capabilitySetHash(caps: string[]): string {
  return sha256Hex([...caps].sort().join("\n"));
}

export function buildPack(
  app: ExtractedApp,
  bundle: BundleResult,
  meta: { typescriptVersion: string; compilerVersion: string },
): { packJson: string; pack: Record<string, unknown> } {
  const schemas = schemaRegistry(app);
  const policyPacks: Record<string, unknown> = {};
  // Dense policy manifest: sorted by key (BTreeMap order) → PolicyId = index
  const sortedPolicyKeys = [...new Set(app.policies.map((p) => p.id))].sort();
  const policyIdMap = new Map<string, number>();
  for (let i = 0; i < sortedPolicyKeys.length; i++) {
    policyIdMap.set(sortedPolicyKeys[i], i);
  }
  const policyManifest: Array<{ id: number; key: string; handlerId: number }> = [];
  for (const key of sortedPolicyKeys) {
    const p = app.policies.find((x) => x.id === key)!;
    policyPacks[key] = {
      id: p.id,
      handler: p.id,
      declaredStatuses: p.declaredStatuses,
      provides: "session",
    };
    policyManifest.push({
      id: policyIdMap.get(key)!,
      key,
      handlerId: policyHandlerIndex(app, key),
    });
  }
  const capabilities = [...new Set(app.routes.flatMap((r) => r.capabilities))].filter((c) => c === "timer");

  const policyHandlerMap = new Map<string, number>();
  for (let i = 0; i < app.policies.length; i++) {
    policyHandlerMap.set(app.policies[i].id, app.routes.length + i);
  }

  function policyHandlerIndex(app: ExtractedApp, policyId: string): number {
    const idx = app.policies.findIndex((p) => p.id === policyId);
    return app.routes.length + idx;
  }

  const sortedSchemaKeys = Object.keys(schemas).sort();
  const schemaKeyToId = new Map<string, number>();
  const schemaManifest: Array<{ id: number; key: string; features: string[]; ir: unknown }> = [];
  for (let i = 0; i < sortedSchemaKeys.length; i++) {
    const k = sortedSchemaKeys[i];
    schemaKeyToId.set(k, i);
    // compatibility markers (M25-001-B): field order matches Rust SchemaDecl
    schemaManifest.push({
      id: i,
      key: k,
      features: featuresOf(schemas[k] as Parameters<typeof featuresOf>[0]),
      ir: schemas[k],
    });
  }

  // M24-005-A: canonical header-name table — security scheme headers plus
  // headers-binding schema properties, sorted and deduped across all routes.
  const headerNameSet = new Set<string>();
  const headerNamesFor = (r: (typeof app.routes)[number]): string[] => {
    const names = new Set<string>();
    const declared = (r as { security?: Array<{ header: string }> }).security;
    if (declared) {
      for (const sec of declared) names.add(sec.header);
    } else if (r.policyId) {
      names.add("authorization");
    }
    for (const n of names) headerNameSet.add(n);
    return [...names].sort();
  };
  const routeHeaderNames = app.routes.map(headerNamesFor);
  const headerNameTable = [...headerNameSet].sort();
  // M24-006-A: compile declared query object fields into canonical dense IDs.
  // Cookie bindings are not yet part of authoring contract, so cookie table
  // remains empty until its dedicated packet adds the binding surface.
  const queryNameSet = new Set<string>();
  const routeQueryNames = app.routes.map((r) => {
    const names = r.queryIr && r.queryIr.kind === "object"
      ? Object.keys((r.queryIr as { properties?: Record<string, unknown> }).properties ?? {}).sort()
      : [];
    for (const name of names) queryNameSet.add(name);
    return names;
  });
  const queryNameTable = [...queryNameSet].sort();

  const packRoutes = app.routes.map((r, routeIdx) => {
    const decision = selectRouteStrategies(r);
    // M26-007-A: status-key order is canonical (numeric ascending), never
    // source-literal order — the fallback default status is the LOWEST
    // declared status when 200 is absent, so authoring order cannot change
    // compiled output.
    const sortedStatusKeys = Object.keys(r.responses)
      .map((k) => Number(k))
      .filter((n) => !isNaN(n))
      .sort((a, b) => a - b)
      .map((n) => String(n));
    const defaultStatus = sortedStatusKeys.includes("200")
      ? 200
      : Number(sortedStatusKeys[0] ?? 200);
    const allowedStatuses = sortedStatusKeys.map((k) => Number(k));
    const responseStrategy = decision.primaryResponseStrategy;

    const paramsSchemaKey = r.paramsIr ? `sch:${r.id}.params` : null;
    const querySchemaKey = r.queryIr ? `sch:${r.id}.query` : null;
    const bodySchemaKey = r.bodyIr ? `sch:${r.id}.body` : null;

    const plan = {
      routeId: routeIdx,
      handlerId: routeIdx,
      policyId: r.policyId ? (policyIdMap.get(r.policyId) ?? null) : null,
      policyHandlerId: r.policyId ? (policyHandlerMap.get(r.policyId) ?? null) : null,
      paramsSchemaId: paramsSchemaKey ? (schemaKeyToId.get(paramsSchemaKey) ?? null) : null,
      querySchemaId: querySchemaKey ? (schemaKeyToId.get(querySchemaKey) ?? null) : null,
      headersSchemaId: null,
      bodySchemaId: bodySchemaKey ? (schemaKeyToId.get(bodySchemaKey) ?? null) : null,
      headerNameIds: routeHeaderNames[routeIdx].map((n) => headerNameTable.indexOf(n)),
      queryNameIds: routeQueryNames[routeIdx].map((n) => queryNameTable.indexOf(n)),
      cookieNameIds: [],
      defaultStatus,
      allowedStatuses,
      fieldNeeds: {
        params: r.paramsIr != null,
        query: r.queryIr != null,
        headers: r.policyId != null,
        body: r.bodyIr != null,
      },
      responseStrategy,
      // M25-007-A: fallback reasons travel with the plan — the runtime
      // rejects a js strategy without a reason from the closed vocabulary
      // (fallback never activates silently)
      ...(decision.validationStrategy === "js"
        ? {
            validationFallbackReason:
              decision.fallbacks.find((f) => ["body", "query", "params"].includes(f.location))?.reason ?? "explicit",
          }
        : {}),
      ...(responseStrategy === "js"
        ? {
            responseFallbackReason:
              decision.fallbacks.find((f) => f.location.startsWith("response."))?.reason ?? "explicit",
          }
        : {}),
      deadlineMs: 5000,
    };

    return {
      id: r.id,
      moduleId: r.moduleId,
      method: r.method,
      path: r.path,
      pathSegments: segsFor(r.path),
      handler: r.id,
      policy: r.policyId ?? null,
      params: r.paramsIr ? { schema: `sch:${r.id}.params`, coerce: "path", contentType: null, limitBytes: 0 } : null,
      query: r.queryIr ? { schema: `sch:${r.id}.query`, coerce: "query", contentType: null, limitBytes: 0 } : null,
      body: r.bodyIr
        ? { schema: `sch:${r.id}.body`, coerce: null, contentType: "application/json", limitBytes: 65536 }
        : null,
      headers: null,
      responses: Object.fromEntries(
        // M26-007-A: canonical key order in serialized output
        sortedStatusKeys.map((k) => {
          const v = r.responses[k] as { ir?: unknown; strategy?: string; problem?: unknown };
          return [
            k,
            {
              schema: v.ir && !v.problem ? `sch:${r.id}.${k}` : null,
              strategy: decision.responseStrategies[k] ?? v.strategy ?? "native",
              problem: v.problem ?? null,
            },
          ];
        }),
      ),
      validationStrategy: decision.validationStrategy,
      nativeLiveness: r.liveness,
      security: r.policyId ? [{ scheme: "bearer", header: "authorization", problemStatus: 401 }] : [],
      capabilities: r.capabilities,
      deadlineMs: 5000,
      plan,
    };
  });
  const functions = [
    ...app.routes.map((r, i) => ({
      id: i,
      key: r.id,
      kind: "route-handler",
    })),
    ...app.policies.map((p, i) => ({
      id: app.routes.length + i,
      key: p.id,
      kind: "policy-handler",
    })),
  ];

  const router = buildSerializedRouter(packRoutes);
  const canonical = rustCanonical(
    packRoutes,
    schemas,
    policyPacks,
    capabilities,
    functions,
    schemaManifest,
    policyManifest,
    router,
  );

  // G0-r1 (C): PUBLIC-ONLY contract hash. Mirrors Rust
  // public_contract_canonical_json exactly:
  // [routes, reachable-schemas(BTreeMap sorted, IR-aware sort), policies-sans-handler]
  const projectBinding = (b: { schema: string | null; coerce: string | null; contentType: string | null; limitBytes: number } | null) =>
    b ? { schema: b.schema, coerce: b.coerce, contentType: b.contentType, limitBytes: b.limitBytes } : null;
  const usedSchemas = new Set<string>();
  const publicRoutes = packRoutes.map((r) => {
    const responsesSorted: Record<string, unknown> = {};
    for (const k of Object.keys(r.responses).sort()) {
      const d = r.responses[k];
      if (d.schema) usedSchemas.add(d.schema);
      responsesSorted[k] = { schema: d.schema, problem: d.problem }; // NO strategy
    }
    for (const b of [r.params, r.query, r.headers, r.body]) {
      if (b?.schema) usedSchemas.add(b.schema);
    }
    return {
      id: r.id,
      method: r.method,
      path: r.path,
      params: projectBinding(r.params),
      query: projectBinding(r.query),
      headers: projectBinding(r.headers),
      body: projectBinding(r.body),
      responses: responsesSorted,
      security: r.security,
    };
  });
  const schemasPublic: Record<string, unknown> = {};
  for (const k of Object.keys(schemas).sort()) {
    if (usedSchemas.has(k)) schemasPublic[k] = sortIR(schemas[k]);
  }
  const policiesPublic: Record<string, unknown> = {};
  for (const k of Object.keys(policyPacks).sort()) {
    const p = policyPacks[k] as { declaredStatuses: unknown; provides: unknown };
    policiesPublic[k] = { declaredStatuses: p.declaredStatuses, provides: p.provides }; // NO handler
  }
  // M25-001-C: whole public-contract view canonicalized (sorted keys), matching
  // q_pack::public_contract_canonical_json
  const publicContractCanonical = JSON.stringify(sortIR([publicRoutes, schemasPublic, policiesPublic]));
  const contractHash = sha(publicContractCanonical).slice(0, 32);

  const pack = {
    formatVersion: 1,
    kind: "velqu.qpack",
    runtimeAbi: 1,
    executionMode: "numeric",
    // M26-002-A: the full runtime fingerprint travels with the pack —
    // rquickjs version and the runtime build hash (sha256 over the
    // runtime identity tuple, mirroring q-pack runtime_build_hash)
    engine: {
      name: "quickjs-ng",
      version: "0.15.1",
      binding: "rquickjs-0.12.2",
      rquickjs: "0.12.2",
      buildHash: runtimeBuildHash(),
    },
    schemaIrVersion: 2,
    contractVersion: 1,
    contractHash,
    builtBy: { compiler: meta.compilerVersion, typescript: meta.typescriptVersion, bun: Bun.version },
    appId: app.appId,
    modules: app.modules,
    entry: "app.js",
    bundle: bundle.code,
    // ADR-0027: production packs embed no source map; debug sources and
    // maps move to the external <pack>.sources.json sidecar (written by
    // buildApp) that the runtime never reads.
    sourceMap: null,
    routes: packRoutes,
    // M26-007-A: schemas embedded in canonical (sorted) key order — the
    // manifest IDs already derive from sorted keys; byte-identical builds
    // must not depend on registry insertion order.
    schemas: Object.fromEntries(sortedSchemaKeys.map((k) => [k, schemas[k]])),
    policies: policyPacks,
    capabilities,
    // M26-002-A: capability-set hash (mirrors q-pack capability_hash)
    capabilityHash: capabilitySetHash(capabilities),
    functions,
    schemaManifest,
    headerNameTable,
    queryNameTable,
    cookieNameTable: [],
    policyManifest,
    router,
    integrity: { algorithm: "sha256", bundleSha256: sha(bundle.code), routesSha256: sha(canonical) },
  };
  return { packJson: JSON.stringify(pack), pack };
}

