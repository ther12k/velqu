export function tsTypeOfIr(ir: Record<string, unknown>): string {
  switch (ir.kind) {
    case "string": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "literal": return JSON.stringify(ir.value);
    case "enum": return (ir.values as unknown[]).map((v) => JSON.stringify(v)).join(" | ");
    case "optional": return tsTypeOfIr(ir.inner as Record<string, unknown>);
    case "nullable": return `${tsTypeOfIr(ir.inner as Record<string, unknown>)} | null`;
    case "array": return `Array<${tsTypeOfIr(ir.items as Record<string, unknown>)}>`;
    case "object": {
      const props = ir.properties as Record<string, Record<string, unknown>>;
      const req = ir.required as string[];
      const fields = Object.entries(props).map(([k, v]) =>
        req.includes(k) ? `${k}: ${tsTypeOfIr(v)}` : `${k}?: ${tsTypeOfIr(v)}`,
      );
      return `{ ${fields.join("; ")} }`;
    }
    case "union":
      return (ir.members as Record<string, unknown>[]).map(tsTypeOfIr).join(" | ");
    case "transform":
      return tsTypeOfIr(ir.output as Record<string, unknown>);
    case "file":
      return "Uint8Array";
    case "problem": {
      // M25-006-C: explicit s.problem responses are the full RFC 9457
      // envelope on the wire (M25-006-A) — the declared literals narrow
      const detail = ir.detail as Record<string, unknown> | undefined;
      const fields = [
        ir.typeUri !== undefined ? `type: "${ir.typeUri}"` : "type: string",
        `title: "${ir.title}"`,
        `status: ${ir.status}`,
        "instance: string",
      ];
      if (detail) fields.push(`detail?: ${tsTypeOfIr(detail)}`);
      return `{ ${fields.join("; ")} }`;
    }
    case "fallback":
      return ir.inner !== undefined ? tsTypeOfIr(ir.inner as Record<string, unknown>) : "unknown";
    default:
      return "unknown";
  }
}

export function contractDts(app: ExtractedApp, contractHash: string): string {
  const lines: string[] = [
    "// @generated by @velqu/compiler — published compact contract (TRT-006)",
    "// Client repositories import ONLY this file; never server source.",
    'import type { RouteContract } from "@velqu/contract";',
    "",
    `export interface Api {`,
  ];
  for (const r of app.routes) {
    const respTs = Object.entries(r.responses).map(([status, decl]) => {
      if (decl.problem) return problemTypeOf(decl.problem, status);
      if (decl.ir) return tsTypeOfIr(decl.ir);
      return "Record<string, unknown>";
    }).map((t, i) => `  ${Object.keys(r.responses)[i]}: ${t}`);
    lines.push(
      `  "${r.id}": RouteContract<`,
      `    "${r.path}",`,
      `    "${r.method}",`,
      `    ${r.paramsIr ? tsTypeOfIr(r.paramsIr) : "Record<string, never>"},`,
      `    ${r.queryIr ? tsTypeOfIr(r.queryIr) : "Record<string, never>"},`,
      `    ${r.bodyIr ? tsTypeOfIr(r.bodyIr) : "undefined"},`,
      `    {`,
      ...respTs.map((t) => `      ${t},`),
      `  }>;`,
    );
  }
  lines.push("};", "", `export const contractHash = "${contractHash}";`, "");
  return lines.join("\n");
}

/**
 * Exact runtime problem envelope per registry id (M25-006-C). The URIs and
 * titles are the frozen URNs from the pack-format spec (mirroring the
 * q-runtime registry); the status literal is the DECLARED response status,
 * so Treaty error narrowing is exact: `if (r.error.status === 401)` types
 * `r.error.problem` as the full unauthorized envelope.
 */
export const PROBLEM_REGISTRY: Record<string, { typeUri: string; title: string }> = {
  validation: { typeUri: "https://velqu.dev/problems/validation", title: "Validation failed" },
  unauthorized: { typeUri: "https://velqu.dev/problems/unauthorized", title: "Unauthorized" },
  "not-found": { typeUri: "https://velqu.dev/problems/not-found", title: "Not Found" },
  method: { typeUri: "https://velqu.dev/problems/method", title: "Method Not Allowed" },
  body: { typeUri: "https://velqu.dev/problems/body", title: "Unsupported body" },
  limit: { typeUri: "https://velqu.dev/problems/limit", title: "Payload too large" },
  timeout: { typeUri: "https://velqu.dev/problems/timeout", title: "Handler deadline exceeded" },
  overload: { typeUri: "https://velqu.dev/problems/overload", title: "Overloaded" },
  internal: { typeUri: "https://velqu.dev/problems/internal", title: "Internal Server Error" },
};

function problemTypeOf(problemId: string, status: string): string {
  const entry = PROBLEM_REGISTRY[problemId] ?? PROBLEM_REGISTRY.internal;
  const members = [
    `type: "${entry.typeUri}"`,
    `title: "${entry.title}"`,
    `status: ${status}`,
    "instance: string",
    "detail?: string",
  ];
  if (problemId === "validation") {
    members.push("errors?: { path: string; code: string; message: string }[]");
  }
  return `{ ${members.join("; ")} }`;
}

/**
 * JSON-Schema form of the same envelope (M25-006-C guardrail: OpenAPI
 * problem schemas match runtime). Required members mirror the runtime
 * builder exactly; enum-constrained type/title/status make generated
 * clients narrow identically to Treaty.
 */
function problemSchemaFor(problemId: string, status: string): Record<string, unknown> {
  const entry = PROBLEM_REGISTRY[problemId] ?? PROBLEM_REGISTRY.internal;
  const properties: Record<string, unknown> = {
    type: { type: "string", enum: [entry.typeUri] },
    title: { type: "string", enum: [entry.title] },
    status: { type: "integer", enum: [Number(status)] },
    instance: { type: "string" },
    detail: { type: "string" },
  };
  if (problemId === "validation") {
    properties.errors = {
      type: "array",
      items: {
        type: "object",
        required: ["path", "code", "message"],
        properties: {
          path: { type: "string" },
          code: { type: "string" },
          message: { type: "string" },
        },
      },
    };
  }
  return {
    type: "object",
    required: ["type", "title", "status", "instance"],
    properties,
  };
}

export function openapiFor(app: ExtractedApp): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  const components: Record<string, Record<string, unknown>> = {};
  const irToSchema = (ir: Record<string, unknown> | null, name: string): unknown => {
    if (!ir) return undefined;
    const conv = (v: Record<string, unknown>): Record<string, unknown> => {
      const out: Record<string, unknown> = { type: v.kind === "integer" || v.kind === "number" ? v.kind === "integer" ? "integer" : "number" : v.kind };
      if (v.kind === "string") {
        if (v.minLength !== undefined) out.minLength = v.minLength;
        if (v.maxLength !== undefined) out.maxLength = v.maxLength;
        if (v.pattern !== undefined) out.pattern = v.pattern;
        if (v.format !== undefined) out.format = v.format;
      }
      if (v.kind === "integer" || v.kind === "number") {
        if (v.minimum !== undefined) out.minimum = v.minimum;
        if (v.maximum !== undefined) out.maximum = v.maximum;
      }
      if (v.kind === "array") out.items = conv(v.items as Record<string, unknown>);
      if (v.kind === "enum") { out.type = "string"; out.enum = v.values; }
      if (v.kind === "literal") { out.type = typeof v.value; out.enum = [v.value]; }
      if (v.kind === "union") {
        out.type = undefined;
        out.oneOf = (v.members as Record<string, unknown>[]).map(conv);
      }
      if (v.kind === "transform") return conv(v.output as Record<string, unknown>);
      if (v.kind === "file") {
        return { type: "string", format: "binary", "x-maxBytes": v.maxBytes, ...(v.contentType !== undefined ? { "x-contentType": v.contentType } : {}) };
      }
      if (v.kind === "problem") {
        const detail = v.detail as Record<string, unknown> | undefined;
        const props: Record<string, unknown> = { title: { type: "string" }, status: { type: "integer" } };
        if (detail) props.detail = conv(detail);
        return {
          type: "object",
          properties: props,
          required: ["title", "status"],
          "x-problem": { ...(v.typeUri !== undefined ? { typeUri: v.typeUri } : {}), title: v.title, status: v.status },
        };
      }
      if (v.kind === "fallback") {
        // explicit fallback stays visible in the projection (ADR-0009)
        return v.inner !== undefined
          ? { ...conv(v.inner as Record<string, unknown>), "x-fallback": v.reason }
          : { "x-fallback": v.reason };
      }
      if (v.kind === "optional" || v.kind === "nullable") return conv(v.inner as Record<string, unknown>);
      if (v.kind === "object") {
        out.type = "object";
        const props: Record<string, unknown> = {};
        for (const [k, p] of Object.entries(v.properties as Record<string, Record<string, unknown>>)) {
          props[k] = conv(p);
        }
        out.properties = props;
        out.required = v.required;
        out.additionalProperties = false;
      }
      return out;
    };
    const schema = conv(ir);
    components[name] = { ...schema } as Record<string, unknown>;
    return { $ref: `#/components/schemas/${name}` };
  };

  for (const r of app.routes) {
    const params = (r.path.match(/:[A-Za-z]+/g) ?? []).map((p) => p.slice(1));
    const op: Record<string, unknown> = {
      operationId: r.id,
      responses: Object.fromEntries(
        Object.entries(r.responses).map(([status, decl]) => [
          status,
          {
            description: decl.problem ? `problem: ${decl.problem}` : "success",
            content:
              decl.ir && !decl.problem
                ? { "application/json": { schema: irToSchema(decl.ir, `${r.id}.resp${status}`) } }
                : decl.problem
                  ? { "application/problem+json": { schema: problemSchemaFor(decl.problem, status) } }
                  : undefined,
          },
        ]),
      ),
    };
    if (params.length || r.paramsIr) {
      op.parameters = params.map((p) => ({
        name: p,
        in: "path",
        required: true,
        schema: { type: "string" },
      }));
    }
    if (r.queryIr) {
      op.parameters = [
        ...((op.parameters as unknown[]) ?? []),
        ...Object.keys((r.queryIr as { properties?: Record<string, unknown> }).properties ?? {}).map((k) => ({
          name: k,
          in: "query",
          required: ((r.queryIr as { required?: string[] }).required ?? []).includes(k),
          schema: { type: "string" },
        })),
      ];
    }
    if (r.bodyIr) {
      op.requestBody = {
        required: true,
        content: { "application/json": { schema: irToSchema(r.bodyIr, `${r.id}.body`) } },
      };
    }
    if (r.policyId) op.security = [{ bearerAuth: [] }];
    const oaPath = r.path.replace(/:([A-Za-z]+)/g, "{$1}");
    (paths[oaPath] ??= {})[r.method.toLowerCase()] = op;
  }
  return {
    openapi: "3.1.0",
    info: { title: app.appId, version: "0.1.0" },
    paths,
    components: {
      schemas: components,
      securitySchemes: app.policies.length ? { bearerAuth: { type: "http", scheme: "bearer" } } : undefined,
    },
  };
}

// ---------------------------------------------------------------- semantic diff

export interface DiffEntry {
  routeId: string;
  kind: "breaking" | "compatible" | "policy-sensitive";
  change: string;
}

export function diffContracts(current: Record<string, unknown>, lock: Record<string, unknown>): DiffEntry[] {
  const out: DiffEntry[] = [];
  const cur = current.routes as Record<string, Record<string, unknown>>;
  const prev = lock.routes as Record<string, Record<string, unknown>>;

  for (const [id, route] of Object.entries(cur)) {
    if (!prev[id]) {
      out.push({ routeId: id, kind: "compatible", change: "route added" });
      continue;
    }
    const p = prev[id];
    if (p.path !== route.path) {
      out.push({ routeId: id, kind: "breaking", change: `path changed ${p.path} → ${route.path}` });
    }
    if (p.method !== route.method) {
      out.push({ routeId: id, kind: "breaking", change: `method changed ${p.method} → ${route.method}` });
    }

    // Status codes diff
    const prevResponses = (p.responses ?? {}) as Record<string, unknown>;
    const curResponses = (route.responses ?? {}) as Record<string, unknown>;
    const prevStatuses = Array.isArray(prevResponses) ? prevResponses : Object.keys(prevResponses);
    const curStatuses = Array.isArray(curResponses) ? curResponses : Object.keys(curResponses);

    for (const s of prevStatuses) {
      if (!curStatuses.includes(s)) {
        out.push({ routeId: id, kind: "breaking", change: `response status ${s} removed` });
      }
    }
    for (const s of curStatuses) {
      if (!prevStatuses.includes(s)) {
        const is2xx = Number(s) >= 200 && Number(s) < 300;
        out.push({
          routeId: id,
          kind: is2xx ? "compatible" : "policy-sensitive",
          change: `response status ${s} added`,
        });
      }
    }

    // Security diff
    const prevSec = p.security ?? null;
    const curSec = route.security ?? null;
    if (prevSec !== curSec) {
      if (!prevSec && curSec) {
        out.push({
          routeId: id,
          kind: "breaking",
          change: `security policy added (${JSON.stringify(curSec)}) — requires authentication`,
        });
      } else if (prevSec && !curSec) {
        out.push({
          routeId: id,
          kind: "policy-sensitive",
          change: `security policy removed (${JSON.stringify(prevSec)}) — endpoint became unauthenticated`,
        });
      } else {
        out.push({
          routeId: id,
          kind: "policy-sensitive",
          change: `security policy changed ${JSON.stringify(prevSec)} → ${JSON.stringify(curSec)}`,
        });
      }
    }

    // Input Schema Diff (params, query, body)
    diffSchemaSection(id, "params", p.params as Record<string, unknown> | null, route.params as Record<string, unknown> | null, out, true);
    diffSchemaSection(id, "query", p.query as Record<string, unknown> | null, route.query as Record<string, unknown> | null, out, true);
    diffSchemaSection(id, "body", p.body as Record<string, unknown> | null, route.body as Record<string, unknown> | null, out, true);

    // Response Schema Diff for common 2xx responses
    if (!Array.isArray(prevResponses) && !Array.isArray(curResponses)) {
      for (const s of curStatuses) {
        if (prevStatuses.includes(s) && Number(s) >= 200 && Number(s) < 300) {
          diffSchemaSection(
            id,
            `response.${s}`,
            prevResponses[s] as Record<string, unknown> | null,
            curResponses[s] as Record<string, unknown> | null,
            out,
            false,
          );
        }
      }
    }
  }

  for (const id of Object.keys(prev)) {
    if (!cur[id]) {
      out.push({ routeId: id, kind: "breaking", change: "route removed" });
    }
  }
  return out;
}

function diffSchemaSection(
  routeId: string,
  section: string,
  prev: Record<string, unknown> | null,
  cur: Record<string, unknown> | null,
  out: DiffEntry[],
  isInput: boolean,
) {
  if (!prev && !cur) return;
  if (!prev && cur) {
    const req = (cur.required as string[]) ?? [];
    if (isInput && req.length > 0) {
      out.push({ routeId, kind: "breaking", change: `${section}: added required schema with required fields [${req.join(", ")}]` });
    } else {
      out.push({ routeId, kind: "compatible", change: `${section}: schema added` });
    }
    return;
  }
  if (prev && !cur) {
    out.push({ routeId, kind: isInput ? "compatible" : "breaking", change: `${section}: schema removed` });
    return;
  }
  if (prev && cur) {
    diffSchemaTypes(routeId, section, prev, cur, out, isInput);
  }
}

function diffSchemaTypes(
  routeId: string,
  section: string,
  prev: Record<string, unknown>,
  cur: Record<string, unknown>,
  out: DiffEntry[],
  isInput: boolean,
) {
  if (prev.kind !== cur.kind) {
    out.push({
      routeId,
      kind: "breaking",
      change: `${section}: type kind changed ${prev.kind} → ${cur.kind}`,
    });
    return;
  }
  if (prev.kind === "object" && cur.kind === "object") {
    const prevProps = (prev.properties ?? {}) as Record<string, Record<string, unknown>>;
    const curProps = (cur.properties ?? {}) as Record<string, Record<string, unknown>>;
    const prevReq = new Set((prev.required as string[]) ?? []);
    const curReq = new Set((cur.required as string[]) ?? []);

    for (const [propName, curProp] of Object.entries(curProps)) {
      if (!prevProps[propName]) {
        const isRequired = curReq.has(propName);
        if (isInput) {
          out.push({
            routeId,
            kind: isRequired ? "breaking" : "compatible",
            change: `${section}.${propName}: ${isRequired ? "required" : "optional"} field added to input`,
          });
        } else {
          out.push({
            routeId,
            kind: "compatible",
            change: `${section}.${propName}: field added to response`,
          });
        }
      } else {
        const prevProp = prevProps[propName];
        if (isInput && !prevReq.has(propName) && curReq.has(propName)) {
          out.push({
            routeId,
            kind: "breaking",
            change: `${section}.${propName}: optional input field became required`,
          });
        }
        diffSchemaTypes(routeId, `${section}.${propName}`, prevProp, curProp, out, isInput);
      }
    }

    for (const propName of Object.keys(prevProps)) {
      if (!curProps[propName]) {
        if (isInput) {
          out.push({ routeId, kind: "compatible", change: `${section}.${propName}: input field removed` });
        } else {
          out.push({ routeId, kind: "breaking", change: `${section}.${propName}: response field removed` });
        }
      }
    }
  } else if (prev.kind === "array" && cur.kind === "array") {
    // M25-008-D: IR v2 scalar constraints participate in the diff
    diffBounds(routeId, section, prev, cur, "minItems", "maxItems", out, isInput);
    if (prev.items && cur.items) {
      diffSchemaTypes(routeId, `${section}[]`, prev.items as Record<string, unknown>, cur.items as Record<string, unknown>, out, isInput);
    }
  } else if (prev.kind === "string" && cur.kind === "string") {
    diffBounds(routeId, section, prev, cur, "minLength", "maxLength", out, isInput);
    diffAdded(routeId, section, prev, cur, "pattern", out, isInput);
    diffAdded(routeId, section, prev, cur, "format", out, isInput);
  } else if (
    (prev.kind === "integer" || prev.kind === "number") &&
    (cur.kind === "integer" || cur.kind === "number")
  ) {
    diffBounds(routeId, section, prev, cur, "minimum", "maximum", out, isInput);
  } else if (prev.kind === "enum" && cur.kind === "enum") {
    const removed = ((prev.values as unknown[]) ?? []).filter(
      (v) => !((cur.values as unknown[]) ?? []).includes(v),
    );
    if (removed.length > 0) {
      out.push({
        routeId,
        kind: isInput ? "breaking" : "compatible",
        change: `${section}: enum value(s) removed [${removed.map((v) => JSON.stringify(v)).join(", ")}]`,
      });
    }
  } else if (prev.kind === "literal" && cur.kind === "literal") {
    if (JSON.stringify(prev.value) !== JSON.stringify(cur.value)) {
      out.push({
        routeId,
        kind: "breaking",
        change: `${section}: literal changed ${JSON.stringify(prev.value)} → ${JSON.stringify(cur.value)}`,
      });
    }
  } else if (prev.kind === "union" && cur.kind === "union") {
    const curMembers = (cur.members as Record<string, unknown>[]).map((m) =>
      JSON.stringify(canonicalIr(m)),
    );
    const removed = (prev.members as Record<string, unknown>[]).filter(
      (m) => !curMembers.includes(JSON.stringify(canonicalIr(m))),
    );
    if (removed.length > 0) {
      out.push({
        routeId,
        kind: isInput ? "breaking" : "compatible",
        change: `${section}: ${removed.length} union member(s) removed`,
      });
    }
  } else if (prev.kind === "nullable" && cur.kind === "nullable") {
    diffSchemaTypes(routeId, section, prev.inner as Record<string, unknown>, cur.inner as Record<string, unknown>, out, isInput);
  } else if (prev.kind === "optional" && cur.kind === "optional") {
    diffSchemaTypes(routeId, section, prev.inner as Record<string, unknown>, cur.inner as Record<string, unknown>, out, isInput);
  } else if (prev.kind === "fallback" && cur.kind === "fallback") {
    if (prev.reason !== cur.reason) {
      out.push({
        routeId,
        kind: "policy-sensitive",
        change: `${section}: fallback reason changed ${prev.reason} → ${cur.reason} (codec path change)`,
      });
    }
    if (prev.inner && cur.inner) {
      diffSchemaTypes(routeId, section, prev.inner as Record<string, unknown>, cur.inner as Record<string, unknown>, out, isInput);
    }
  }
}

/** M25-008-D: numeric-ish bounds (min/max, lengths, item counts). */
function diffBounds(
  routeId: string,
  section: string,
  prev: Record<string, unknown>,
  cur: Record<string, unknown>,
  minKey: string,
  maxKey: string,
  out: DiffEntry[],
  isInput: boolean,
) {
  const prevMin = prev[minKey] as number | undefined;
  const curMin = cur[minKey] as number | undefined;
  const prevMax = prev[maxKey] as number | undefined;
  const curMax = cur[maxKey] as number | undefined;

  // tightening: a floor appears or rises, a ceiling appears or falls —
  // previously-accepted input now rejects (breaking); responses narrow
  // (policy-sensitive: clients may receive narrower data than typed)
  const minTightened = curMin !== undefined && (prevMin === undefined || curMin > prevMin);
  const maxTightened = curMax !== undefined && (prevMax === undefined || curMax < prevMax);
  if (minTightened || maxTightened) {
    out.push({
      routeId,
      kind: isInput ? "breaking" : "policy-sensitive",
      change: `${section}: bounds tightened (${minKey}: ${prevMin ?? "—"} → ${curMin ?? "—"}, ${maxKey}: ${prevMax ?? "—"} → ${curMax ?? "—"})`,
    });
  }

  // loosening: a floor falls/disappears or a ceiling rises/disappears —
  // input accepts more (compatible); responses may carry wider data
  const minLoosened = prevMin !== undefined && (curMin === undefined || curMin < prevMin);
  const maxLoosened = prevMax !== undefined && (curMax === undefined || curMax > prevMax);
  if (minLoosened || maxLoosened) {
    out.push({
      routeId,
      kind: "compatible",
      change: `${section}: bounds loosened (${minKey}: ${prevMin ?? "—"} → ${curMin ?? "—"}, ${maxKey}: ${prevMax ?? "—"} → ${curMax ?? "—"})`,
    });
  }
}

/** M25-008-D: a scalar constraint member appearing/changing/vanishing. */
function diffAdded(
  routeId: string,
  section: string,
  prev: Record<string, unknown>,
  cur: Record<string, unknown>,
  key: string,
  out: DiffEntry[],
  isInput: boolean,
) {
  if (prev[key] === undefined && cur[key] !== undefined) {
    out.push({
      routeId,
      kind: isInput ? "breaking" : "policy-sensitive",
      change: `${section}: ${key} constraint added (${JSON.stringify(cur[key])})`,
    });
  } else if (prev[key] !== undefined && cur[key] === undefined) {
    out.push({
      routeId,
      kind: "compatible",
      change: `${section}: ${key} constraint removed`,
    });
  } else if (prev[key] !== cur[key]) {
    out.push({
      routeId,
      kind: isInput ? "breaking" : "policy-sensitive",
      change: `${section}: ${key} changed ${JSON.stringify(prev[key])} → ${JSON.stringify(cur[key])}`,
    });
  }
}

/** Canonical member form for union comparison (sorted keys). */
function canonicalIr(ir: Record<string, unknown>): Record<string, unknown> {
  return Object.keys(ir)
    .sort()
    .reduce<Record<string, unknown>>((acc, k) => {
      acc[k] = ir[k];
      return acc;
    }, {});
}
