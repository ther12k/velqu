//! Rust source generator for the M25-002-A schema-aware projection prototype.
//!
//! `generate(&corpus)` emits the exact contents of `codec_bench/generated.rs`
//! (one fused decode/validate function per benchmark schema plus a
//! `supports` classifier). The committed file and the generator output are
//! locked together by the `generated_source_is_current` test, so the
//! "generated codec" claim is reproducible: change the corpus or the
//! generator, re-emit, and the test forces the file to match.
//!
//! Emitted decoder semantics mirror `q_schema_runtime::validate` with
//! `Source::Body` exactly — same error paths, codes, and messages — so the
//! differential tests can assert byte-level parity with the generic
//! validator:
//! - objects: unknown-key errors (input order) → missing-required errors
//!   (declared order) → per-property errors (sorted property order),
//!   accumulated across properties;
//! - arrays: min/max items checked first, then items short-circuit on the
//!   first failure;
//! - `Optional`/`Nullable`/`Fallback { inner: Some }` wrappers are
//!   transparent, with `Optional` defaults applied for absent-or-null
//!   members.

use q_schema_runtime::SchemaIr;
use serde_json::Value;

use super::schemas::BenchSchema;

/// Guard mirroring the emitted `supports` classifier. Keep the logic in sync
/// with the `supports` template below (the `generated_supports_matches_guard`
/// test locks them together on a probe set covering every IR variant).
pub fn schema_supported(ir: &SchemaIr) -> bool {
    match ir {
        SchemaIr::String {
            pattern, format, ..
        } => pattern.is_none() && format.is_none(),
        SchemaIr::Integer { .. } | SchemaIr::Number { .. } | SchemaIr::Boolean => true,
        SchemaIr::Optional { inner, .. } | SchemaIr::Nullable { inner } => schema_supported(inner),
        SchemaIr::Array { items, .. } => schema_supported(items),
        SchemaIr::Object { properties, .. } => properties.values().all(|b| schema_supported(b)),
        SchemaIr::Fallback {
            inner: Some(inner), ..
        } => schema_supported(inner),
        _ => false,
    }
}

/// Rust constructor expression for a scalar default literal.
fn value_ctor(v: &Value) -> String {
    match v {
        Value::Null => "Value::Null".to_string(),
        Value::Bool(b) => format!("Value::Bool({b})"),
        Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                format!("Value::Number(Number::from({i}))")
            } else {
                let f = n.as_f64().expect("benchmark defaults are finite");
                format!("Number::from_f64({f:?}).map(Value::Number).unwrap()")
            }
        }
        Value::String(s) => format!("Value::String({:?}.to_string())", s),
        _ => panic!("benchmark defaults must be scalar literals"),
    }
}

pub fn generate(corpus: &[BenchSchema]) -> String {
    for s in corpus {
        assert!(
            schema_supported(&s.ir),
            "generator refuses unsupported schema {}",
            s.name
        );
    }
    let mut g = Generator {
        out: String::new(),
        n: 0,
    };
    g.header(corpus);
    for s in corpus {
        g.decode_fn(s);
    }
    g.out
}

struct Generator {
    out: String,
    n: usize,
}

impl Generator {
    fn id(&mut self) -> usize {
        self.n += 1;
        self.n
    }

    fn header(&mut self, corpus: &[BenchSchema]) {
        let names: Vec<&str> = corpus.iter().map(|s| s.name).collect();
        let names = names.join(", ");
        self.out.push_str(&format!(
            "// @generated by crates/q-bench-support/src/bin/codec_bench/generator.rs — DO NOT EDIT.\n\
             // Corpus: M25-002-A ({names}).\n\
             // Regenerate: cargo run -p q-bench-support --bin q-codec-bench -- --emit-generated crates/q-bench-support/src/bin/codec_bench/generated.rs\n\
             // Fused decode/validate projections over the parsed JSON value. Error paths,\n\
             // codes, and messages are byte-identical to q_schema_runtime::validate\n\
             // (Source::Body); `supports` fails closed outside the supported subset.\n\n\
             use q_schema_runtime::{{FieldError, SchemaIr}};\n\
             use serde_json::{{Map, Number, Value}};\n\n\
             #[rustfmt::skip]\n\
             fn fe(path: &str, code: &str, message: String) -> FieldError {{\n\
             \x20   FieldError {{ path: path.to_string(), code: code.to_string(), message }}\n\
             }}\n\n\
             #[rustfmt::skip]\n\
             fn join_path(base: &str, key: &str) -> String {{\n\
             \x20   if base.is_empty() {{ key.to_string() }} else {{ format!(\"{{}}.{{}}\", base, key) }}\n\
             }}\n\n\
             #[rustfmt::skip]\n\
             pub fn supports(ir: &SchemaIr) -> bool {{\n\
             \x20   match ir {{\n\
             \x20       SchemaIr::String {{ pattern, format, .. }} => pattern.is_none() && format.is_none(),\n\
             \x20       SchemaIr::Integer {{ .. }} | SchemaIr::Number {{ .. }} | SchemaIr::Boolean => true,\n\
             \x20       SchemaIr::Optional {{ inner, .. }} | SchemaIr::Nullable {{ inner }} => supports(inner),\n\
             \x20       SchemaIr::Array {{ items, .. }} => supports(items),\n\
             \x20       SchemaIr::Object {{ properties, .. }} => properties.values().all(|b| supports(b)),\n\
             \x20       SchemaIr::Fallback {{ inner: Some(inner), .. }} => supports(inner),\n\
             \x20       _ => false,\n\
             \x20   }}\n\
             }}\n\n\
             #[rustfmt::skip]\n\
             pub fn decode(name: &str, v: &Value) -> Option<Result<Value, Vec<FieldError>>> {{\n\
             \x20   match name {{\n"
        ));
        for s in corpus {
            self.out.push_str(&format!(
                "        \"{}\" => Some(decode_{}(v)),\n",
                s.name, s.name
            ));
        }
        self.out.push_str("        _ => None,\n    }\n}\n");
    }

    fn decode_fn(&mut self, s: &BenchSchema) {
        self.out.push_str(&format!(
            "\n#[rustfmt::skip]\npub fn decode_{}(v: &Value) -> Result<Value, Vec<FieldError>> {{\n\
             \x20   let p0: String = String::new();\n",
            s.name
        ));
        let r = self.emit_node(&s.ir, "v", "p0", 1);
        self.out.push_str(&format!("    {r}\n}}\n"));
    }

    /// Emits a binding `r{id}: Result<Value, Vec<FieldError>>` for `ir`,
    /// reading the value from `val` (a `&Value` expression) and reporting
    /// errors under the path held in `path` (a `String` binding in scope).
    fn emit_node(&mut self, ir: &SchemaIr, val: &str, path: &str, indent: usize) -> String {
        let r = format!("r{}", self.id());
        let pad = "    ".repeat(indent);
        match ir {
            SchemaIr::Object {
                properties,
                required,
            } => {
                self.emit_object(&r, val, path, indent, properties, required);
            }
            SchemaIr::Array {
                items,
                min_items,
                max_items,
            } => {
                self.emit_array(&r, val, path, indent, items, *min_items, *max_items);
            }
            SchemaIr::String {
                min_length,
                max_length,
                ..
            } => {
                self.emit_string(&r, val, path, &pad, *min_length, *max_length);
            }
            SchemaIr::Integer { minimum, maximum } => {
                self.emit_integer(&r, val, path, &pad, *minimum, *maximum);
            }
            SchemaIr::Number { minimum, maximum } => {
                self.emit_number(&r, val, path, &pad, *minimum, *maximum);
            }
            SchemaIr::Boolean => {
                self.out.push_str(&format!(
                    "{pad}let {r}: Result<Value, Vec<FieldError>> = match {val}.as_bool() {{\n\
                     {pad}    Some(b) => Ok(Value::Bool(b)),\n\
                     {pad}    None => Err(vec![fe(&{path}, \"type\", \"expected boolean\".to_string())]),\n\
                     {pad}}};\n"
                ));
            }
            SchemaIr::Fallback {
                inner: Some(inner), ..
            } => {
                return self.emit_node(inner, val, path, indent);
            }
            SchemaIr::Optional { inner, default } => {
                // mirrors validate_node: null → default (or Null), else inner
                let d = default
                    .as_ref()
                    .map(value_ctor)
                    .unwrap_or_else(|| "Value::Null".to_string());
                self.out.push_str(&format!(
                    "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
                     {pad}    if {val}.is_null() {{ return Ok({d}); }}\n"
                ));
                let ri = self.emit_node(inner, val, path, indent + 1);
                self.out.push_str(&format!("{pad}    {ri}\n{pad}}})();\n"));
            }
            SchemaIr::Nullable { inner } => {
                self.out.push_str(&format!(
                    "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
                     {pad}    if {val}.is_null() {{ return Ok(Value::Null); }}\n"
                ));
                let ri = self.emit_node(inner, val, path, indent + 1);
                self.out.push_str(&format!("{pad}    {ri}\n{pad}}})();\n"));
            }
            other => panic!("emit_node refuses unsupported node {other:?}"),
        }
        r
    }

    #[allow(clippy::too_many_arguments)]
    fn emit_object(
        &mut self,
        r: &str,
        val: &str,
        path: &str,
        indent: usize,
        properties: &std::collections::BTreeMap<String, Box<SchemaIr>>,
        required: &[String],
    ) {
        let pad = "    ".repeat(indent);
        let keys: Vec<&str> = properties.keys().map(|k| k.as_str()).collect();
        let arm = if keys.is_empty() {
            String::new()
        } else {
            format!("            \"{}\" => {{}}\n", keys.join("\" | \""))
        };
        self.out.push_str(&format!(
            "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
             {pad}    let obj = match {val}.as_object() {{\n\
             {pad}        Some(o) => o,\n\
             {pad}        None => return Err(vec![fe(&{path}, \"type\", \"expected object\".to_string())]),\n\
             {pad}    }};\n\
             {pad}    let mut errors: Vec<FieldError> = Vec::new();\n\
             {pad}    for key in obj.keys() {{\n\
             {pad}        match key.as_str() {{\n\
             {arm}\
             {pad}            _ => errors.push(fe(&join_path(&{path}, key), \"additional\", \"unknown field\".to_string())),\n\
             {pad}        }}\n\
             {pad}    }}\n"
        ));
        for req in required {
            self.out.push_str(&format!(
                "{pad}    if !obj.contains_key(\"{req}\") {{\n\
                 {pad}        errors.push(fe(&join_path(&{path}, \"{req}\"), \"required\", \"missing required field\".to_string()));\n\
                 {pad}    }}\n"
            ));
        }
        self.out.push_str(&format!(
            "{pad}    if !errors.is_empty() {{ return Err(errors); }}\n\
             {pad}    let mut out = Map::new();\n"
        ));
        for (key, prop) in properties {
            self.emit_property(key, prop, path, indent + 1);
        }
        self.out.push_str(&format!(
            "{pad}    if !errors.is_empty() {{ return Err(errors); }}\n\
             {pad}    Ok(Value::Object(out))\n\
             {pad}}})();\n"
        ));
    }

    fn emit_property(&mut self, key: &str, prop: &SchemaIr, parent: &str, indent: usize) {
        let pad = "    ".repeat(indent);
        let p = format!("p{}", self.id());
        let v = format!("v{}", self.id());
        match prop {
            SchemaIr::Optional { inner, default } => {
                self.out.push_str(&format!(
                    "{pad}let {p}: String = join_path(&{parent}, \"{key}\");\n\
                     {pad}if let Some({v}) = obj.get(\"{key}\") {{\n\
                     {pad}    if {v}.is_null() {{\n"
                ));
                match default {
                    Some(d) => self.out.push_str(&format!(
                        "{pad}        out.insert(\"{key}\".to_string(), {});\n",
                        value_ctor(d)
                    )),
                    None => self.out.push_str(&format!(
                        "{pad}        out.insert(\"{key}\".to_string(), Value::Null);\n"
                    )),
                }
                self.out.push_str(&format!("{pad}    }} else {{\n"));
                let r = self.emit_node(inner, &v, &p, indent + 2);
                self.out.push_str(&format!(
                    "{pad}        match {r} {{ Ok(nv) => {{ out.insert(\"{key}\".to_string(), nv); }} Err(mut e) => {{ errors.append(&mut e); }} }}\n\
                     {pad}    }}\n"
                ));
                if let Some(d) = default {
                    self.out.push_str(&format!(
                        "{pad}}} else {{\n\
                         {pad}    out.insert(\"{key}\".to_string(), {});\n\
                         {pad}}}\n",
                        value_ctor(d)
                    ));
                } else {
                    self.out.push_str(&format!("{pad}}}\n"));
                }
            }
            SchemaIr::Nullable { inner } => {
                self.out.push_str(&format!(
                    "{pad}let {p}: String = join_path(&{parent}, \"{key}\");\n\
                     {pad}if let Some({v}) = obj.get(\"{key}\") {{\n\
                     {pad}    if {v}.is_null() {{\n\
                     {pad}        out.insert(\"{key}\".to_string(), Value::Null);\n\
                     {pad}    }} else {{\n"
                ));
                let r = self.emit_node(inner, &v, &p, indent + 2);
                self.out.push_str(&format!(
                    "{pad}        match {r} {{ Ok(nv) => {{ out.insert(\"{key}\".to_string(), nv); }} Err(mut e) => {{ errors.append(&mut e); }} }}\n\
                     {pad}    }}\n\
                     {pad}}}\n"
                ));
            }
            SchemaIr::Fallback {
                inner: Some(inner), ..
            } => {
                self.emit_plain_property(key, inner, parent, indent);
            }
            other => self.emit_plain_property(key, other, parent, indent),
        }
    }

    fn emit_plain_property(&mut self, key: &str, prop: &SchemaIr, parent: &str, indent: usize) {
        let pad = "    ".repeat(indent);
        let p = format!("p{}", self.id());
        let v = format!("v{}", self.id());
        self.out.push_str(&format!(
            "{pad}let {p}: String = join_path(&{parent}, \"{key}\");\n\
             {pad}if let Some({v}) = obj.get(\"{key}\") {{\n"
        ));
        let r = self.emit_node(prop, &v, &p, indent + 1);
        self.out.push_str(&format!(
            "{pad}    match {r} {{ Ok(nv) => {{ out.insert(\"{key}\".to_string(), nv); }} Err(mut e) => {{ errors.append(&mut e); }} }}\n\
             {pad}}}\n"
        ));
    }

    #[allow(clippy::too_many_arguments)]
    fn emit_array(
        &mut self,
        r: &str,
        val: &str,
        path: &str,
        indent: usize,
        items: &SchemaIr,
        min_items: Option<u64>,
        max_items: Option<u64>,
    ) {
        let pad = "    ".repeat(indent);
        self.out.push_str(&format!(
            "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
             {pad}    let arr = match {val}.as_array() {{\n\
             {pad}        Some(a) => a,\n\
             {pad}        None => return Err(vec![fe(&{path}, \"type\", \"expected array\".to_string())]),\n\
             {pad}    }};\n"
        ));
        if let Some(min) = min_items {
            self.out.push_str(&format!(
                "{pad}    if (arr.len() as u64) < {min} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"minItems\", \"must have at least {min} items\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        if let Some(max) = max_items {
            self.out.push_str(&format!(
                "{pad}    if (arr.len() as u64) > {max} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"maxItems\", \"must have at most {max} items\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        let i = format!("i{}", self.id());
        let item = format!("item{}", self.id());
        let ip = format!("p{}", self.id());
        self.out.push_str(&format!(
            "{pad}    let mut items: Vec<Value> = Vec::with_capacity(arr.len());\n\
             {pad}    for ({i}, {item}) in arr.iter().enumerate() {{\n\
             {pad}        let {ip}: String = format!(\"{{}}[{{}}]\", &{path}, {i});\n"
        ));
        let ir = self.emit_node(items, &item, &ip, indent + 2);
        self.out.push_str(&format!(
            "{pad}        items.push({ir}?);\n\
             {pad}    }}\n\
             {pad}    Ok(Value::Array(items))\n\
             {pad}}})();\n"
        ));
    }

    fn emit_string(
        &mut self,
        r: &str,
        val: &str,
        path: &str,
        pad: &str,
        min_length: Option<u64>,
        max_length: Option<u64>,
    ) {
        let s = format!("s{}", self.id());
        self.out.push_str(&format!(
            "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
             {pad}    let {s} = match {val}.as_str() {{\n\
             {pad}        Some(s) => s,\n\
             {pad}        None => return Err(vec![fe(&{path}, \"type\", \"expected string\".to_string())]),\n\
             {pad}    }};\n"
        ));
        if let Some(min) = min_length {
            self.out.push_str(&format!(
                "{pad}    if ({s}.len() as u64) < {min} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"minLength\", \"must be at least {min} characters\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        if let Some(max) = max_length {
            self.out.push_str(&format!(
                "{pad}    if ({s}.len() as u64) > {max} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"maxLength\", \"must be at most {max} characters\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        self.out.push_str(&format!(
            "{pad}    Ok(Value::String({s}.to_string()))\n\
             {pad}}})();\n"
        ));
    }

    fn emit_integer(
        &mut self,
        r: &str,
        val: &str,
        path: &str,
        pad: &str,
        minimum: Option<i64>,
        maximum: Option<i64>,
    ) {
        let i = format!("n{}", self.id());
        self.out.push_str(&format!(
            "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
             {pad}    let {i} = match {val}.as_i64() {{\n\
             {pad}        Some(n) => n,\n\
             {pad}        None => return Err(vec![fe(&{path}, \"type\", \"expected integer\".to_string())]),\n\
             {pad}    }};\n"
        ));
        if let Some(min) = minimum {
            self.out.push_str(&format!(
                "{pad}    if {i} < {min} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"minimum\", \"must be at least {min}\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        if let Some(max) = maximum {
            self.out.push_str(&format!(
                "{pad}    if {i} > {max} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"maximum\", \"must be at most {max}\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        self.out.push_str(&format!(
            "{pad}    Ok(Value::Number(Number::from({i})))\n\
             {pad}}})();\n"
        ));
    }

    fn emit_number(
        &mut self,
        r: &str,
        val: &str,
        path: &str,
        pad: &str,
        minimum: Option<f64>,
        maximum: Option<f64>,
    ) {
        let f = format!("f{}", self.id());
        self.out.push_str(&format!(
            "{pad}let {r}: Result<Value, Vec<FieldError>> = (|| {{\n\
             {pad}    let {f} = match {val}.as_f64() {{\n\
             {pad}        Some(f) => f,\n\
             {pad}        None => return Err(vec![fe(&{path}, \"type\", \"expected number\".to_string())]),\n\
             {pad}    }};\n"
        ));
        if let Some(min) = minimum {
            self.out.push_str(&format!(
                "{pad}    if {f} < {min:?} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"minimum\", \"must be at least {min:?}\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        if let Some(max) = maximum {
            self.out.push_str(&format!(
                "{pad}    if {f} > {max:?} {{\n\
                 {pad}        return Err(vec![fe(&{path}, \"maximum\", \"must be at most {max:?}\".to_string())]);\n\
                 {pad}    }}\n"
            ));
        }
        self.out.push_str(&format!(
            "{pad}    match Number::from_f64({f}) {{\n\
             {pad}        Some(num) => Ok(Value::Number(num)),\n\
             {pad}        None => Err(vec![fe(&{path}, \"type\", \"not a finite number\".to_string())]),\n\
             {pad}    }}\n\
             {pad}}})();\n"
        ));
    }
}
